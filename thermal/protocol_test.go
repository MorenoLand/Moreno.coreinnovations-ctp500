// The frames below are the byte sequences hardcoded in the original C# app;
// Frame/Crc8 must reproduce them exactly.
func TestFramesMatchOriginal(t *testing.T) {
	cases := map[string][2][]byte{
		"info":     {GetInfo(), {0x51, 0x78, 0xA8, 0x00, 0x01, 0x00, 0x00, 0x00, 0xFF}},
		"battery":  {GetBattery(), {0x51, 0x78, 0xBA, 0x00, 0x01, 0x00, 0x00, 0x00, 0xFF}},
		"status":   {GetStatus(), {0x51, 0x78, 0xA3, 0x00, 0x01, 0x00, 0x00, 0x00, 0xFF}},
		"devid":    {GetDevID(), {0x51, 0x78, 0xBB, 0x00, 0x01, 0x00, 0x01, 0x07, 0xFF}},
		"stop":     {StopPrint(), {0x51, 0x78, 0xA6, 0x00, 0x01, 0x00, 0x05, 0x1B, 0xFF}},
		"img":      {PrintModeImg(), {0x51, 0x78, 0xBE, 0x00, 0x01, 0x00, 0x00, 0x00, 0xFF}},
		"text":     {PrintModeText(), {0x51, 0x78, 0xBE, 0x00, 0x01, 0x00, 0x01, 0x07, 0xFF}},
		"selftest": {SelfTest(), {0x51, 0x78, 0xA6, 0x00, 0x0B, 0x00, 0xAA, 0x55, 0x17, 0x38, 0x44, 0x5F, 0x5F, 0x5F, 0x44, 0x38, 0x2C, 0xA1, 0xFF}},
		"d1":       {SetDensity(0), {0x51, 0x78, 0xA4, 0x00, 0x01, 0x00, 0x31, 0x97, 0xFF}},
		"d2":       {SetDensity(1), {0x51, 0x78, 0xA4, 0x00, 0x01, 0x00, 0x32, 0x9E, 0xFF}},
		"d3":       {SetDensity(2), {0x51, 0x78, 0xA4, 0x00, 0x01, 0x00, 0x33, 0x99, 0xFF}},
		"d4":       {SetDensity(3), {0x51, 0x78, 0xA4, 0x00, 0x01, 0x00, 0x34, 0x8C, 0xFF}},
		"d5":       {SetDensity(4), {0x51, 0x78, 0xA4, 0x00, 0x01, 0x00, 0x35, 0x8B, 0xFF}},
	}
	for name, c := range cases {
		if !bytes.Equal(c[0], c[1]) {
			t.Errorf("%s: got % X want % X", name, c[0], c[1])
		}
	}
}

func TestFeedFrame(t *testing.T) {
	got := FeedLines(0x0102)
	want := []byte{0x51, 0x78, 0xA1, 0x00, 0x02, 0x00, 0x02, 0x01, Crc8([]byte{0x02, 0x01}), 0xFF}
	if !bytes.Equal(got, want) {
		t.Fatalf("got % X want % X", got, want)
	}
}

func TestRenderDimensions(t *testing.T) {
	g := Render(&Doc{Texts: []TextLayer{{Text: "Hi", Size: 24}}}, 128, true)
	if g.Bounds().Dx() != PaperW || g.Bounds().Dy() < 64 {
		t.Fatalf("bad size %v", g.Bounds())
	}
	bits, bpr, h := Pack(g)
	if bpr != PaperW/8 || len(bits) != bpr*h {
		t.Fatalf("bad pack %d %d %d", bpr, h, len(bits))
	}
	dark := 0
	for _, b := range bits {
		if b != 0 {
			dark++
		}
	}
	if dark == 0 {
		t.Fatal("text rendered nothing")
	}
}
